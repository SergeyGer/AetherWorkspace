using System.Text.RegularExpressions;
using Aether.Contracts.Capabilities;
using Aether.Contracts.Errors;
using Aether.Contracts.Json;
using Aether.Contracts.Models;

namespace Aether.Contracts.Studio;

/// <summary>Bounded draft kinds supported by the review-only contract studio (v0.6 AW-034).</summary>
public enum ContractDraftKind
{
    RegistryEntry,
    JsonSchema,
    ProtoMessage,
}

/// <summary>Review lifecycle; generated drafts start untrusted and never execute or auto-approve.</summary>
public enum ContractDraftStatus
{
    Untrusted,
    Reviewed,
    Applied,
    Rejected,
}

/// <summary>
/// A generated contract draft. Content is a strict JSON envelope containing the untrusted
/// payload; it is never an executable artifact and cannot mutate the active registry by itself.
/// </summary>
public sealed record ContractDraft(
    string DraftId,
    ContractDraftKind Kind,
    string TargetName,
    ContractDraftStatus Status,
    bool Untrusted,
    DateTimeOffset CreatedAtUtc,
    string PayloadJson);

/// <summary>Deterministic, bounded templates for documented public/synthetic schemas only.</summary>
public static partial class ContractDraftGenerator
{
    public const string SchemaVersion = "1.0";

    public static ContractDraft GenerateRegistryEntry(
        string appId,
        string displayName,
        IReadOnlyList<string>? capabilities = null,
        IReadOnlyList<string>? contextTypes = null,
        IReadOnlyList<string>? classifications = null,
        DateTimeOffset? createdAtUtc = null)
    {
        ValidateIdentifier(appId, "app id", AppIdPattern());
        ValidateName(displayName, "display name");
        var caps = capabilities ?? ["context.subscribe"];
        foreach (var capability in caps)
        {
            if (!CapabilityNames.All.Contains(capability))
            {
                throw new AetherContractException(AetherErrorCodes.PlanInvalidJson, $"Unknown capability '{capability}'.");
            }
        }

        var contexts = contextTypes ?? ["fdc3.instrument"];
        foreach (var context in contexts)
        {
            if (context is not ("fdc3.instrument" or "fdc3.organization"))
            {
                throw new AetherContractException(AetherErrorCodes.PlanInvalidJson, $"Unsupported context type '{context}'.");
            }
        }

        var levels = classifications ?? ["PUBLIC", "INTERNAL", "RESTRICTED"];
        foreach (var level in levels)
        {
            if (level is not ("PUBLIC" or "INTERNAL" or "RESTRICTED"))
            {
                throw new AetherContractException(AetherErrorCodes.PlanInvalidJson, $"Unsupported classification '{level}'.");
            }
        }

        var entry = new
        {
            appId,
            displayName,
            launchable = true,
            executable = "{DOTNET}",
            arguments = new[] { "{SAMPLES_DLL}", "--app", appId },
            workingDirectory = "{AETHER_HOME}",
            capabilities = caps,
            allowedChannels = new[] { "default" },
            allowedContextTypes = contexts,
            allowedClassifications = levels,
            maxInstances = 1,
            launchTimeoutSeconds = 15,
        };
        var payload = AetherJson.Serialize(new { manifestVersion = "1.0", apps = new[] { entry } });
        return CreateDraft(ContractDraftKind.RegistryEntry, appId, payload, createdAtUtc);
    }

    public static ContractDraft GenerateProtoMessage(string messageName, string fieldName, string fieldType = "string", DateTimeOffset? createdAtUtc = null)
    {
        ValidateIdentifier(messageName, "message name", PascalPattern());
        ValidateIdentifier(fieldName, "field name", SnakePattern());
        if (fieldType is not ("string" or "int32" or "int64" or "bool" or "double"))
        {
            throw new AetherContractException(AetherErrorCodes.PlanInvalidJson, $"Unsupported proto field type '{fieldType}'.");
        }

        var payload = "syntax = \"proto3\";\n\npackage aether.studio.v1;\n\n// Untrusted draft generated by Aether.ContractStudio. Review before use.\nmessage " +
            messageName + " {\n  " + fieldType + " " + fieldName + " = 1;\n}\n";
        return CreateDraft(ContractDraftKind.ProtoMessage, messageName, AetherJson.Serialize(new { proto = payload }), createdAtUtc);
    }

    public static ContractDraft GenerateSchema(string schemaName, DateTimeOffset? createdAtUtc = null)
    {
        ValidateIdentifier(schemaName, "schema name", PascalPattern());
        var payload = AetherJson.Serialize(new
        {
            schema = "http://json-schema.org/draft-07/schema#",
            title = schemaName,
            type = "object",
            additionalProperties = false,
            properties = new Dictionary<string, object> { ["name"] = new { type = "string", minLength = 1 } },
            required = new[] { "name" },
        });
        return CreateDraft(ContractDraftKind.JsonSchema, schemaName, payload, createdAtUtc);
    }

    private static ContractDraft CreateDraft(ContractDraftKind kind, string targetName, string payloadJson, DateTimeOffset? createdAtUtc)
    {
        var created = createdAtUtc ?? DateTimeOffset.UtcNow;
        var draftId = $"{kind.ToString().ToLowerInvariant()}-{targetName.ToLowerInvariant()}-{created:yyyyMMddHHmmss}";
        return new ContractDraft(draftId, kind, targetName, ContractDraftStatus.Untrusted, Untrusted: true, created, payloadJson);
    }

    private static void ValidateIdentifier(string value, string description, Regex pattern)
    {
        if (string.IsNullOrWhiteSpace(value) || value.Length > 64 || !pattern.IsMatch(value))
        {
            throw new AetherContractException(AetherErrorCodes.PlanInvalidJson, $"The {description} '{value}' is not a valid bounded identifier.");
        }
    }

    private static void ValidateName(string value, string description)
    {
        if (string.IsNullOrWhiteSpace(value) || value.Length > 128 || value.Any(char.IsControl))
        {
            throw new AetherContractException(AetherErrorCodes.PlanInvalidJson, $"The {description} is invalid.");
        }
    }

    [GeneratedRegex("^[a-z][a-z0-9._-]{2,63}$", RegexOptions.CultureInvariant)]
    private static partial Regex AppIdPattern();

    [GeneratedRegex("^[A-Z][A-Za-z0-9]{2,63}$", RegexOptions.CultureInvariant)]
    private static partial Regex PascalPattern();

    [GeneratedRegex("^[a-z][a-z0-9_]{1,63}$", RegexOptions.CultureInvariant)]
    private static partial Regex SnakePattern();
}

/// <summary>Review-only validation for generated drafts (no compilation, no execution).</summary>
public static class ContractDraftValidator
{
    public static IReadOnlyList<string> Validate(ContractDraft draft, string? activeRegistryJson = null)
    {
        ArgumentNullException.ThrowIfNull(draft);
        var issues = new List<string>();
        if (draft.Untrusted is false || draft.Status != ContractDraftStatus.Untrusted)
        {
            issues.Add("A generated draft must be marked untrusted until explicit review.");
        }

        if (string.IsNullOrWhiteSpace(draft.PayloadJson))
        {
            issues.Add("The draft payload is empty.");
            return issues;
        }

        switch (draft.Kind)
        {
            case ContractDraftKind.RegistryEntry:
                try
                {
                    var document = AetherJson.DeserializeStrict<AppManifestDocument>(draft.PayloadJson);
                    foreach (var app in document.Apps)
                    {
                        if (activeRegistryJson is not null)
                        {
                            var active = AetherJson.DeserializeStrict<AppManifestDocument>(activeRegistryJson);
                            if (active.Apps.Any(existing => string.Equals(existing.AppId, app.AppId, StringComparison.Ordinal)))
                            {
                                issues.Add($"App id '{app.AppId}' already exists in the active registry.");
                            }
                        }
                    }
                }
                catch (AetherContractException exception)
                {
                    issues.Add(exception.Message);
                }

                break;
            case ContractDraftKind.JsonSchema:
                try
                {
                    using var _ = System.Text.Json.JsonDocument.Parse(draft.PayloadJson);
                }
                catch (System.Text.Json.JsonException exception)
                {
                    issues.Add("The schema payload is not valid JSON: " + exception.Message);
                }

                break;
            case ContractDraftKind.ProtoMessage:
                var proto = System.Text.Json.JsonDocument.Parse(draft.PayloadJson).RootElement.GetProperty("proto").GetString() ?? "";
                if (!proto.Contains("syntax = \"proto3\";", StringComparison.Ordinal) ||
                    !proto.Contains("message ", StringComparison.Ordinal) ||
                    proto.Count(character => character == '{') != proto.Count(character => character == '}'))
                {
                    issues.Add("The proto draft is not a bounded proto3 message snippet.");
                }

                break;
            default:
                issues.Add("Unsupported draft kind.");
                break;
        }

        return issues;
    }
}
