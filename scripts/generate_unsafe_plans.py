#!/usr/bin/env python3
"""Generates the documented 100-entry unsafe-plan negative corpus.

The corpus drives the executor's acceptance test: every entry must be denied by
strict JSON parsing or deterministic validation before any side effect. Entries
are synthetic and contain no real data.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "fixtures", "unsafe-plans", "unsafe-plans.json")


def plan(plan_id, steps, schema="1.0", description=None):
    value = {"schemaVersion": schema, "planId": plan_id, "steps": steps}
    if description is not None:
        value["description"] = description
    return value


def launch(app_id):
    return {"action": "LaunchApp", "appId": app_id}


def publish(context_ref):
    return {"action": "PublishContext", "contextRef": context_ref}


def arrange(layout):
    return {"action": "ArrangeWindows", "layout": layout}


def summarize(context_ref, mode=None):
    step = {"action": "SummarizeContext", "contextRef": context_ref}
    if mode is not None:
        step["mode"] = mode
    return step


def show(text):
    return {"action": "ShowStatus", "statusText": text}


entries = []
index = 0


def add(category, expected_code, value, expect_parse_failure=False):
    global index
    index += 1
    entries.append({
        "id": f"unsafe-{index:03d}",
        "category": category,
        "expectedCode": expected_code,
        "expectParseFailure": expect_parse_failure,
        "plan": value,
    })


# 10 unknown actions
for i in range(10):
    add("unknown-action", "plan.action.unknown",
        plan(f"unsafe-action-{i:02d}", [{"action": "ExecShell", "statusText": "echo pwned"}]))

# 10 unknown applications
for i in range(10):
    add("unknown-app", "plan.app.unknown",
        plan(f"unsafe-app-{i:02d}", [launch(f"sample.unknown{i}")]))

# 10 path traversal context references
for i in range(10):
    add("path-context-ref", "plan.unsafe_content",
        plan(f"unsafe-path-{i:02d}", [publish(f"../../secrets/{i}")]))

# 10 URL-like context references
for i in range(10):
    add("url-context-ref", "plan.unsafe_content",
        plan(f"unsafe-url-{i:02d}", [publish(f"https://attacker.example/{i}")]))

# 10 plans over the configured action budget
for i in range(10):
    steps = [show(f"step {n}") for n in range(8)]
    add("too-many-steps", "plan.steps.too_many", plan(f"unsafe-budget-{i:02d}", steps))

# 10 unsupported schema majors
for i in range(10):
    add("unsupported-schema", "plan.schema.version_unsupported",
        plan(f"unsafe-schema-{i:02d}", [show("hello")], schema="2.0" if i % 2 == 0 else "0.9"))

# 10 cloud-mode summary attempts (untrusted plan may not select a cloud provider)
for i in range(10):
    add("summarize-mode-cloud", "plan.mode.unsupported",
        plan(f"unsafe-mode-{i:02d}", [summarize("synthetic.exposure.northstar", mode="cloud")]))

# 10 unknown trusted context references
for i in range(10):
    add("unknown-context", "plan.context.unknown",
        plan(f"unsafe-context-{i:02d}", [summarize(f"synthetic.unknown.{i}")]))

# 5 unsupported layouts
for i in range(5):
    add("unsupported-layout", "plan.layout.unsupported",
        plan(f"unsafe-layout-{i:02d}", [arrange("horizontal-split")]))

# 5 invalid status text values
for i in range(5):
    text = "" if i % 2 == 0 else "x" * 300
    add("invalid-status-text", "plan.status.invalid", plan(f"unsafe-status-{i:02d}", [show(text)]))

# 5 duplicate launch steps
for i in range(5):
    add("duplicate-launch", "plan.app.duplicate_launch",
        plan(f"unsafe-duplicate-{i:02d}", [launch("sample.watchlist"), launch("sample.watchlist")]))

# 5 plans carrying unknown/forbidden JSON fields (strict parsing must reject)
for i in range(5):
    value = plan(f"unsafe-field-{i:02d}", [show("looks valid")])
    value["executable"] = "cmd.exe /c calc"
    add("forbidden-json-field", "plan.invalid_json", value, expect_parse_failure=True)

assert len(entries) == 100, f"expected 100 corpus entries, got {len(entries)}"
document = {
    "_comment": "Synthetic negative corpus. Generated by scripts/generate_unsafe_plans.py; do not edit by hand.",
    "corpusVersion": "1.0",
    "count": len(entries),
    "entries": entries,
}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8") as handle:
    json.dump(document, handle, indent=2)
    handle.write("\n")
print(f"wrote {OUT} with {len(entries)} entries")
